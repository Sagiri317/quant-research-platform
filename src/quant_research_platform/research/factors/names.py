def _macro_variable_name(variable):
    if variable in _MACRO_NAMES:
        return _MACRO_NAMES[variable]
    if variable.endswith("_vix_ratio"):
        return _MACRO_NAMES[variable.removesuffix("_vix_ratio")] + "／VIX比率"
    match = re.fullmatch(
        r"us_cftc_(sp500|nasdaq)_(leveraged_net_share|asset_manager_net_share|"
        r"leveraged_net_contracts)",
        variable,
    )
    if match:
        index = {"sp500": "标普500", "nasdaq": "纳斯达克"}[match[1]]
        position = {
            "leveraged_net_share": "杠杆基金净持仓占比",
            "asset_manager_net_share": "资产管理机构净持仓占比",
            "leveraged_net_contracts": "杠杆基金净持仓合约数",
        }[match[2]]
        return "美国CFTC" + index + position
    match = re.fullmatch(r"us_cboe_(equity|index|total)_put_call", variable)
    if match:
        scope = {"equity": "股票", "index": "指数", "total": "全市场"}[match[1]]
        return "美国Cboe" + scope + "认沽认购成交比"
    raise KeyError(variable)


def factor_display_name(column):
    """Render known definitions without inferring an economic effect from results."""
    if column.startswith("feature_pre_neutral_"):
        return "中性化前·" + factor_display_name(column[20:])
    if column.startswith("feature_"):
        return "处理后·" + factor_display_name(column[8:])
    if column.startswith("ml_"):
        from quant_research_platform.research.factors.macro_liquidity import definitions

        recipe = definitions.RECIPES[column]
        kind, variable = recipe[:2]
        if kind == "series":
            return _macro_variable_name(variable) + "·" + _TRANSFORMS[recipe[2]]
        if kind == "state":
            return _macro_variable_name(variable)
        if kind in {"interaction", "industry_interaction"}:
            scope = "行业平均" if kind == "industry_interaction" else "个股"
            return (
                factor_display_name("ml_" + variable)
                + "×"
                + scope
                + factor_display_name(recipe[2])
            )
        if kind == "matched_beta":
            return _macro_variable_name(variable) + "冲击×自身敏感度"
        method = "控制市场后的敏感度" if recipe[2] == "partial_beta" else "敏感度"
        return "自身对" + _macro_variable_name(variable) + "的" + method
    if column in _NAMES:
        return _NAMES[column]
    match = re.fullmatch(r"momentum_(\d+)_(\d+)", column)
    if match:
        return f"{match[1]}日动量（剔除最近{match[2]}日）"
    match = re.fullmatch(r"(.+)_(\d+)([dsm])", column)
    if match:
        unit = {"d": "日", "s": "秒", "m": "分钟"}[match[3]]
        return match[2] + unit + "·" + _NAMES[match[1]]
    raise KeyError(column)
