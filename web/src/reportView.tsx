type ReportBlock =
  | { type: 'title'; text: string }
  | { type: 'section'; text: string }
  | { type: 'paragraph'; text: string }
  | { type: 'item'; label: string; value: string }

export function ReportView({ markdown }: { markdown: string }) {
  const blocks = translateReport(markdown)
  const [title, ...content] = blocks
  return (
    <div className="report-view">
      <div className="report-hero">
        <span>评估报告</span>
        <h4>
          {title?.type === 'title' ? title.text : '量化研究平台评估报告'}
        </h4>
        <p>报告由量化研究平台根据提供的因子或预测面板生成。</p>
      </div>
      <div className="report-body">
        {content.map((block, index) => {
          if (block.type === 'section') {
            return <h5 key={`${block.text}-${index}`}>{block.text}</h5>
          }
          if (block.type === 'item') {
            return (
              <div className="report-kv" key={`${block.label}-${index}`}>
                <span>{block.label}</span>
                <strong>{block.value}</strong>
              </div>
            )
          }
          return (
            <p className="report-line" key={`${block.text}-${index}`}>
              {block.text}
            </p>
          )
        })}
      </div>
    </div>
  )
}

function translateReport(markdown: string): ReportBlock[] {
  const lines = markdown.split(/\r?\n/).map((line) => line.trim()).filter(Boolean)
  const blocks: ReportBlock[] = []
  for (const line of lines) {
    if (line.startsWith('# ')) {
      blocks.push({ type: 'title', text: translateReportTitle(line.slice(2)) })
      continue
    }
    if (line.startsWith('## ')) {
      blocks.push({ type: 'section', text: translateReportSection(line.slice(3)) })
      continue
    }
    if (line.startsWith('- ')) {
      blocks.push(parseReportItem(line.slice(2)))
      continue
    }
    const paragraph = translateReportParagraph(line)
    if (paragraph) {
      blocks.push({ type: 'paragraph', text: paragraph })
    }
  }
  if (!blocks.some((block) => block.type === 'title')) {
    blocks.unshift({ type: 'title', text: '量化研究平台评估报告' })
  }
  if (!blocks.some((block) => block.type === 'section' && block.text === '指标表')) {
    blocks.push({ type: 'section', text: '指标表' })
    blocks.push({
      type: 'paragraph',
      text: '指标明细可在下方 CSV 明细浏览和下载区查看。',
    })
  }
  return blocks
}

function translateReportTitle(title: string): string {
  return title
    .replace(/\bcore evaluation\b/i, 'core 评估')
    .replace(/\bevaluation\b/i, '评估')
    .replace(/\bReport\b/i, '量化研究平台报告')
}

function translateReportSection(section: string): string {
  const normalized = section.toLowerCase()
  if (normalized === 'summary') {
    return '摘要'
  }
  if (normalized === 'metrics') {
    return '指标表'
  }
  if (normalized === 'boundary') {
    return '边界说明'
  }
  return section
}

function translateReportParagraph(line: string): string {
  if (line.startsWith('This report is generated by ')) {
    return '报告由量化研究平台根据提供的因子或预测面板生成。'
  }
  if (line.startsWith('Synthetic/toy adapter only')) {
    return '仅 synthetic/toy adapter；不包含真实数据、API 连接、凭证、模拟交易、实盘交易或投资建议。'
  }
  if (line === 'Synthetic evidence.') {
    return 'Synthetic/toy 证据摘要。'
  }
  return line
}

function parseReportItem(text: string): ReportBlock {
  const normalized = text.replace(/`/g, '')
  const [rawLabel, ...rest] = normalized.split(':')
  if (rest.length === 0) {
    return { type: 'paragraph', text: normalized }
  }
  return {
    type: 'item',
    label: translateReportLabel(rawLabel.trim()),
    value: translateReportValue(rest.join(':').trim()),
  }
}

function translateReportLabel(label: string): string {
  const labels: Record<string, string> = {
    project: '项目',
    kind: '研究类型',
    'data stage': '数据阶段',
    'rows evaluated': '评估行数',
    features: '因子列',
  }
  return labels[label] ?? label
}

function translateReportValue(value: string): string {
  return value.replace(/\brows\b/g, '行')
}
